ARROW_MAP = {

    103: Key.up,
    108: Key.down,
    105: Key.left,
    106: Key.right,
}


# ============================================================
# CONVERSION CODE LINUX → TOUCHE PYNPUT
# ============================================================

def linux_code_to_key(code):

    # --------------------------------------------------------
    # Touches spéciales
    # --------------------------------------------------------

    if code in KEY_MAP:
        return KEY_MAP[code]

    # --------------------------------------------------------
    # Pavé numérique
    # --------------------------------------------------------

    if code in NUMPAD_MAP:
        return NUMPAD_MAP[code]

    if code in NUMPAD_SPECIAL_MAP:
        return NUMPAD_SPECIAL_MAP[code]

    # --------------------------------------------------------
    # Flèches
    # --------------------------------------------------------

    if code in ARROW_MAP:
        return ARROW_MAP[code]

    # --------------------------------------------------------
    # Touches caractères
    # --------------------------------------------------------

    if code in CHAR_MAP:
        return CHAR_MAP[code]

    # --------------------------------------------------------
    # Touche inconnue
    # --------------------------------------------------------

    return None


# ============================================================
# GESTION D'UNE TOUCHE
# ============================================================

